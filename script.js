/* 問題表示 */

function showQuestion(){

    isAnswered = false;

    progress.textContent =
        "問題 " + (currentQuestion + 1) +
        " / " + quizQuestions.length;

    question.textContent =
        quizQuestions[currentQuestion].text ||
        quizQuestions[currentQuestion].question;

    result.textContent = "";
}

/* 回答判定 */

function checkAnswer(userAnswer){

    if(isAnswered) return;

    isAnswered = true;

    const q = quizQuestions[currentQuestion];

    if(userAnswer === q.answer){

        correctCount++;

        result.textContent = "正解";
        result.className = "correct";

    }else{

        result.textContent = "不正解";
        result.className = "incorrect";

        wrongQuestions.push(q);

        if(
            currentMode === "mock" ||
            currentMode === "honMock"
        ){

            wrongCount++;

            const limit =
                currentMode === "honMock"
                ? 11
                : 6;

            if(wrongCount >= limit){

                setTimeout(showResult, 500);
                return;

            }
        }
    }

    setTimeout(() => {

        currentQuestion++;

        if(currentQuestion < quizQuestions.length){

            showQuestion();

        }else{

            showResult();

        }

    }, 800);
}

/* 結果表示 */

function showResult(){

    const total = quizQuestions.length;

    const percent =
        Math.round((correctCount / total) * 100);

    let isPass;

    if(currentMode === "mock"){

        isPass = correctCount >= 45;

    }else if(currentMode === "honMock"){

        isPass = correctCount >= 90;

    }else{

        isPass = percent >= 90;

    }

    progress.textContent = "リザルト";

    let html =
        "<h2>クイズ終了！</h2>" +
        "<h1 style='color:" +
        (isPass ? "red" : "blue") +
        "'>" +
        (isPass ? "合格" : "不合格") +
        "</h1>" +
        "<p>正解数：" + correctCount + "</p>" +
        "<p>不正解数：" + wrongQuestions.length + "</p>" +
        "<p>正答率：" + percent + "%</p>";

    if(wrongQuestions.length > 0){

        html += "<h3>間違えた問題</h3><ul class='wrong-list'>";

        wrongQuestions.forEach(q => {

            html +=
                "<li style='margin-bottom:20px;'>" +
                (q.text || q.question) +
                "<br>（正解は" +
                (q.answer ? "〇" : "✕") +
                "）</li>";

        });

        html += "</ul>";
    }

    html +=
        "<br><button onclick='goHome()'>ホームへ戻る</button>";

    question.innerHTML = html;

    document.querySelector(".answer-buttons").style.display = "none";
}

